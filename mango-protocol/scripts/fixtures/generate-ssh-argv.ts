/**
 * Generates `spec/fixtures/1/ssh-argv.json`, the corpus both SDKs build the
 * same `ssh` command line from.
 *
 * The argv is produced by the reference builder rather than typed by hand, so
 * an option the preset gains cannot be transcribed into the corpus wrongly.
 * The committed file is the fixture; CI regenerates it and fails when the
 * output differs, so an edit here is a deliberate corpus change — and the Rust
 * suite reading the same file is what proves the two SDKs agree.
 *
 * @example
 * bun ./scripts/fixtures/generate-ssh-argv.ts          # rewrite the file
 * bun ./scripts/fixtures/generate-ssh-argv.ts --check  # exit 1 when stale
 */

import { type SshArgvOptions, sshArgv } from '../../packages/protocol/src/transports/ssh';

const OUTPUT = new URL('../../spec/fixtures/1/ssh-argv.json', import.meta.url);

/** The field a refusal is about; the Rust error carries the same name. */
type Reason = 'host' | 'user' | 'port' | 'connectTimeoutSeconds' | 'command';

interface Accepted {
  readonly name: string;
  readonly options: SshArgvOptions;
}

interface Rejected {
  readonly name: string;
  /** Loosely typed: several cases are values the type system already refuses. */
  readonly options: Record<string, unknown>;
  readonly reason: Reason;
}

const ACCEPTED: readonly Accepted[] = [
  {
    name: 'y_host_and_command',
    options: { host: 'build-box', command: ['mango-runtime'] },
  },
  {
    name: 'y_user_and_quoted_arguments',
    options: {
      host: 'build-box',
      user: 'deploy',
      command: ['/opt/mango/runtime', '--stdio', '--name', "it's mine"],
    },
  },
  {
    name: 'y_identity_file_and_port',
    options: {
      host: 'build-box',
      port: 2222,
      identityFile: '/home/u/.ssh/id_ed25519',
      command: ['mango-runtime', '--stdio'],
    },
  },
  {
    name: 'y_home_relative_remote_path',
    options: { host: 'build-box', command: ['~/bin/mango-runtime', '--stdio'] },
  },
  {
    name: 'y_custom_connect_timeout',
    options: { host: 'build-box', command: ['mango-runtime'], connectTimeoutSeconds: 20 },
  },
];

