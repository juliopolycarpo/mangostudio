/** The words the refusal message must contain, so `reason` is not a label nobody checks. */
const MESSAGE_PREFIX: Record<Reason, string> = {
  host: 'ssh host is',
  user: 'ssh user is',
  port: 'ssh port is',
  connectTimeoutSeconds: 'ssh connectTimeoutSeconds is',
  command: 'ssh command is',
};

function accepted(item: Accepted): Record<string, unknown> {
  return {
    name: item.name,
    verdict: 'accept',
    options: item.options,
    argv: sshArgv(item.options),
  };
}

function rejected(item: Rejected): Record<string, unknown> {
  let message: string | undefined;
  try {
    sshArgv(item.options as unknown as SshArgvOptions);
  } catch (cause) {
    message = cause instanceof Error ? cause.message : String(cause);
  }
  if (message === undefined) {
    throw new Error(`${item.name}: expected sshArgv to refuse these options, it returned an argv`);
  }
  const prefix = MESSAGE_PREFIX[item.reason];
  if (!message.startsWith(prefix)) {
    throw new Error(
      `${item.name}: refusal is ${JSON.stringify(message)}; expected one starting ${JSON.stringify(prefix)}`
    );
  }
  return { name: item.name, verdict: 'reject', options: item.options, reason: item.reason };
}

const document = {
  $comment:
    'ssh launcher argv: both SDKs must build the same command line for the same inputs. Generated by scripts/fixtures/generate-ssh-argv.ts; edit the generator, never this file. A reject case names the field the preset refuses; an implementation whose types already refuse the value (a port outside 1-65535, say) satisfies the case by construction.',
  cases: [...ACCEPTED.map(accepted), ...REJECTED.map(rejected)],
};

const text = `${JSON.stringify(document, null, 2)}\n`;
const check = process.argv.includes('--check');
const current = await Bun.file(OUTPUT)
  .text()
  .catch(() => '');

if (check) {
  if (current !== text) {
    console.error(
      'spec/fixtures/1/ssh-argv.json is stale; run bun ./scripts/fixtures/generate-ssh-argv.ts'
    );
    process.exit(1);
  }
  console.warn('ssh-argv.json is up to date');
} else {
  await Bun.write(OUTPUT, text);
  console.warn(`wrote ${document.cases.length} cases to spec/fixtures/1/ssh-argv.json`);
}
