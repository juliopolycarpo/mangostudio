/**
 * Generates the throwaway modules that embed the built frontend into a
 * standalone binary. Both modules are emitted under `.mango/out/embed/`
 * (gitignored, never committed): a manifest that imports every file in
 * `apps/frontend/dist` with Bun's file loader — `bun build --compile` then
 * embeds the bytes and resolves each import to an embedded path servable via
 * `Bun.file()` — and an entry that registers the manifest before booting the
 * real CLI.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { distFilePath, listDistFiles } from '@mangostudio/shared/utils/dist-files';
import { type PrecompressedVariant, writePrecompressedVariants } from './precompress-assets';

export interface EmbedModuleOptions {
  /** Built frontend directory (apps/frontend/dist). */
  distDir: string;
  /** Output directory for the generated modules (.mango/out/embed). */
  embedDir: string;
  /** Absolute path to apps/api/src/server/embedded-frontend.ts. */
  registryModulePath: string;
  /** Absolute path to the real CLI entrypoint (apps/api/src/index.ts). */
  apiEntryPath: string;
}

export interface EmbedModules {
  entryPath: string;
  manifestPath: string;
  fileCount: number;
  /** Precompressed gzip/Brotli copies embedded beside the identity files. */
  variantCount: number;
  /** Total bytes those copies add to the binary. */
  variantBytes: number;
}

/**
 * Renders the manifest module: one file-loader import per dist file, keyed by URL path,
 * plus the precompressed variants of those files under a second export.
 *
 * Variants are deliberately not keys of `embeddedFrontend`: every key there is a
 * public route and one entry in the doctor's file count, and a `.br` copy is
 * neither. They are keyed by the *identity* URL path they encode.
 */
export function renderFrontendManifestModule(
  distDir: string,
  urlPaths: readonly string[],
  variants: readonly PrecompressedVariant[] = []
): string {
  const imports = urlPaths.map((urlPath, index) => {
    const filePath = distFilePath(distDir, urlPath);
    return `import f${index} from ${JSON.stringify(filePath)} with { type: 'file' };`;
  });
  const entries = urlPaths.map((urlPath, index) => `  ${JSON.stringify(urlPath)}: f${index},`);
  const variantImports = variants.map(
    (variant, index) =>
      `import v${index} from ${JSON.stringify(variant.filePath)} with { type: 'file' };`
  );

  return [
    '// Generated by scripts/lib/embed-frontend.ts — do not edit or commit.',
    ...imports,
    ...variantImports,
    '',
    'export const embeddedFrontend: Record<string, string> = {',
    ...entries,
    '};',
    '',
    '/** Identity URL path → coding → embedded path of the precompressed copy. */',
    'export const embeddedFrontendEncodings: Record<string, Record<string, string>> = {',
    ...renderEncodingEntries(variants),
    '};',
    '',
  ].join('\n');
}

/** One object entry per identity path, listing its codings. Variants arrive grouped by path. */
function renderEncodingEntries(variants: readonly PrecompressedVariant[]): string[] {
  const byPath = new Map<string, string[]>();
  variants.forEach((variant, index) => {
    const codings = byPath.get(variant.urlPath) ?? [];
    codings.push(`${JSON.stringify(variant.coding)}: v${index}`);
    byPath.set(variant.urlPath, codings);
  });
  return [...byPath].map(
    ([urlPath, codings]) => `  ${JSON.stringify(urlPath)}: { ${codings.join(', ')} },`
  );
}

/** Renders the compile entrypoint: register the embedded manifest, then boot the CLI. */
export function renderEmbedEntryModule(registryModulePath: string, apiEntryPath: string): string {
  return [
    '// Generated by scripts/lib/embed-frontend.ts — do not edit or commit.',
    `import { registerEmbeddedFrontend } from ${JSON.stringify(registryModulePath)};`,
    "import { embeddedFrontend, embeddedFrontendEncodings } from './frontend-manifest';",
    '',
    'registerEmbeddedFrontend(embeddedFrontend, embeddedFrontendEncodings);',
    '',
    '// Dynamic import so registration happens before any server module runs.',
    `await import(${JSON.stringify(apiEntryPath)});`,
    '',
  ].join('\n');
}

/**
 * Refuse to compile a binary that would ship without its frontend.
 *
 * The embedded manifest is the only place a binary's assets come from — there
 * is no disk fallback to catch a miss. Without this the failure is silent and
 * late: an empty manifest compiles, the binary boots, `registerEmbeddedSpa`
 * finds no `/index.html`, and every route answers API-only. That looks like a
 * server problem to whoever hits it, an hour and a release pipeline away from
 * the build that caused it.
 *
 * `/index.html` specifically, not just a non-empty walk: it is the one file the
 * shell and every SPA deep link resolve to, and a dist that somehow has assets
 * without it is no more servable than an empty one.
 */
function assertEmbeddable(distDir: string, urlPaths: readonly string[]): void {
  if (urlPaths.includes('/index.html')) return;
  throw new Error(
    `Cannot embed a frontend from ${distDir}: no /index.html among ${urlPaths.length} file(s). ` +
      'Build the frontend before compiling the binary.'
  );
}

/** Directory under `embedDir` that holds the generated variants. */
const VARIANTS_DIRNAME = 'variants';

/** Writes manifest + entry modules and returns the entry to compile. // Usage: writeEmbedModules(options) */
export function writeEmbedModules(options: EmbedModuleOptions): EmbedModules {
  const urlPaths = listDistFiles(options.distDir);
  assertEmbeddable(options.distDir, urlPaths);
  mkdirSync(options.embedDir, { recursive: true });

  // Cleared first: `embedDir` outlives a build, and a variant of a file the
  // frontend no longer ships must not survive to be embedded by mistake.
  const variantsDir = join(options.embedDir, VARIANTS_DIRNAME);
  rmSync(variantsDir, { recursive: true, force: true });
  const variants = writePrecompressedVariants(options.distDir, variantsDir, urlPaths);

  const manifestPath = join(options.embedDir, 'frontend-manifest.ts');
  writeFileSync(manifestPath, renderFrontendManifestModule(options.distDir, urlPaths, variants));

  const entryPath = join(options.embedDir, 'entry.ts');
  writeFileSync(
    entryPath,
    renderEmbedEntryModule(options.registryModulePath, options.apiEntryPath)
  );

  return {
    entryPath,
    manifestPath,
    fileCount: urlPaths.length,
    variantCount: variants.length,
    variantBytes: variants.reduce((total, variant) => total + variant.compressedBytes, 0),
  };
}
