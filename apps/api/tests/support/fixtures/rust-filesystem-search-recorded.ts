/**
 * Filesystem search answers recorded from the retired in-process TypeScript
 * runtime, for `rust-filesystem-search-compat.integration.test.ts` to hold the
 * Rust runtime to. Recorded on Linux against that suite's fixture tree, in the
 * order the TypeScript walk returned them.
 *
 * Placeholders stand for the machine-dependent scratch paths: `<ROOT>` is the
 * fixture directory the search runs in, `<HOME>` its parent (the scratch
 * `MANGO_HOME`). Every path separator is `/`.
 *
 * The recorded order is the filesystem's own enumeration order, which is also
 * machine-dependent, so the suite compares matches order-insensitively; a
 * capped (`truncated`) glob result is held to membership in the uncapped one.
 */

import type { RuntimeGrepResult } from '@mangostudio/shared/runtime-contract';

/** One `fs.glob` call and the TypeScript answer's `matches` and `truncated`. */
export interface RecordedGlob {
  readonly pattern: string;
  readonly includeDotfiles: boolean;
  readonly maxResults: number;
  readonly absolute: boolean;
  readonly matches: readonly string[];
  readonly truncated: boolean;
}

/**
 * One `fs.grep` call and the TypeScript answer. `scansStarFile` marks answers
 * whose `filesScanned` counts the POSIX-only `a*b.txt` fixture.
 */
export interface RecordedGrep {
  readonly scansStarFile: boolean;
  readonly result: RuntimeGrepResult;
}

