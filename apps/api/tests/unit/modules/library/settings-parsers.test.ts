import { describe, expect, it } from 'bun:test';

import { parseJsonSettings } from '../../../../src/modules/library/infrastructure/settings-parsers/json';
import { parsePermissionRules } from '../../../../src/modules/library/infrastructure/settings-parsers/rules';
import { parseTomlSettings } from '../../../../src/modules/library/infrastructure/settings-parsers/toml';

describe('settings parsers', () => {
  it('returns a typed failure instead of throwing for malformed JSON', () => {
    expect(parseJsonSettings('{"permissions":', { homeDir: '/home/ada' })).toEqual({
      parsed: false,
      failureReason: 'invalid-json',
      fields: [],
    });
  });

  it('collapses Codex project tables into a count', () => {
    const projects = Array.from(
      { length: 40 },
      (_, index) => `[projects."/home/ada/project-${index}"]\ntrust_level = "trusted"`
    ).join('\n\n');

    expect(parseTomlSettings(`model = "gpt-5"\n\n${projects}`, { homeDir: '/home/ada' })).toEqual({
      parsed: true,
      fields: [
        {
          path: 'model',
          presentation: 'value',
          value: 'gpt-5',
        },
        {
          path: 'projects.count',
          presentation: 'value',
          value: '40',
        },
      ],
    });
  });

  it('extracts rules as pattern-to-decision rows', () => {
    expect(
      parsePermissionRules(
        [
          {
            name: 'default.rules',
            content: [
              '# generated by Codex',
              '',
              'prefix_rule(pattern = ["git", "status"], decision = "allow")',
              'prefix_rule(pattern = ["rm"], decision = "forbidden")',
            ].join('\n'),
          },
        ],
        { homeDir: '/home/ada' }
      )
    ).toEqual({
      parsed: true,
      fields: [
        {
          path: 'default.rules[3].pattern',
          presentation: 'value',
          value: '["git", "status"]',
        },
        {
          path: 'default.rules[3].decision',
          presentation: 'value',
          value: 'allow',
        },
        {
          path: 'default.rules[4].pattern',
          presentation: 'value',
          value: '["rm"]',
        },
        {
          path: 'default.rules[4].decision',
          presentation: 'value',
          value: 'forbidden',
        },
      ],
    });
  });

  describe('Codex .rules grammar', () => {
    const options = { homeDir: '/home/ada' };
    const parse = (content: string) =>
      parsePermissionRules([{ name: 'a.rules', content }], options);
    const valuesOf = (content: string) => {
      const result = parse(content);
      if (!result.parsed)
        throw new Error(`expected parsed rules, received ${result.failureReason}`);
      return result.fields.map((field) => ({
        path: field.path,
        value: field.presentation === 'value' ? field.value : field.presentation,
      }));
    };

    it('reads a rule split across lines, with comments between arguments', () => {
      expect(
        valuesOf(
          [
            'prefix_rule(',
            '    pattern = ["gh", "pr", "view"],  # the command prefix',
            '    # why it is allowed',
            '    decision = "prompt",',
            '    justification = "Viewing PRs is allowed with approval",',
            ')',
          ].join('\n')
        )
      ).toEqual([
        { path: 'a.rules[1].pattern', value: '["gh", "pr", "view"]' },
        { path: 'a.rules[1].decision', value: 'prompt' },
      ]);
    });

    it('displays a pattern the same way however the file wraps it', () => {
      const wrapped = valuesOf(
        'prefix_rule(\n  pattern = [\n    "git",\n    ["push", "pull"],\n  ],\n  decision = "prompt",\n)'
      );
      const oneLine = valuesOf(
        'prefix_rule(pattern = ["git", ["push", "pull"]], decision = "prompt")'
      );
      expect(wrapped.map((field) => field.value)).toEqual(oneLine.map((field) => field.value));
      expect(wrapped[0]?.value).toBe('["git", ["push", "pull"]]');
    });

    it('numbers each rule by the line its call starts on', () => {
      expect(
        valuesOf(
          [
            'prefix_rule(',
            '  pattern = ["ls"],',
            ')',
            '',
            'prefix_rule(',
            '  pattern = ["rm"],',
            '  decision = "forbidden",',
            ')',
          ].join('\n')
        ).map((field) => field.path)
      ).toEqual([
        'a.rules[1].pattern',
        'a.rules[1].decision',
        'a.rules[5].pattern',
        'a.rules[5].decision',
      ]);
    });

    it('defaults the decision to allow, as Codex does', () => {
      expect(valuesOf('prefix_rule(pattern = ["ls"])')).toEqual([
        { path: 'a.rules[1].pattern', value: '["ls"]' },
        { path: 'a.rules[1].decision', value: 'allow' },
      ]);
    });

    it('does not read parentheses, brackets, comments or keywords inside strings as structure', () => {
      expect(
        valuesOf(
          [
            'prefix_rule(',
            '  pattern = ["echo", ")", "]", "# not a comment", \'decision = "forbidden"\'],',
            '  justification = "closes ) early ( and says pattern = [] decision = \\"forbidden\\"",',
            '  decision = "prompt",',
            ')',
          ].join('\n')
        )
      ).toEqual([
        {
          path: 'a.rules[1].pattern',
          value: '["echo", ")", "]", "# not a comment", "decision = \\"forbidden\\""]',
        },
        { path: 'a.rules[1].decision', value: 'prompt' },
      ]);
    });

    it('accepts triple-quoted and raw strings, and skips match examples', () => {
      expect(
        valuesOf(
          [
            'prefix_rule(',
            '  pattern = [r"C:\\tools\\run"],',
            '  justification = """spans',
            '  two lines )""",',
            '  match = [["cmd", "a"], "cmd b"],',
            '  not_match = ["cmd c"],',
            '  decision = "allow",',
            ')',
          ].join('\n')
        )
      ).toEqual([
        { path: 'a.rules[1].pattern', value: '["C:\\\\tools\\\\run"]' },
        { path: 'a.rules[1].decision', value: 'allow' },
      ]);
    });

    it('treats a file of only comments and blank lines as an empty rule set', () => {
      expect(parse('# nothing here\n\n   \n# still nothing\n')).toEqual({
        parsed: true,
        fields: [],
      });
      expect(parse('')).toEqual({ parsed: true, fields: [] });
    });

    it('recognizes host_executable without turning it into a rule', () => {
      expect(
        valuesOf(
          'host_executable(name = "git", paths = ["/usr/bin/git"])\nprefix_rule(pattern = ["git"], decision = "prompt")'
        )
      ).toEqual([
        { path: 'a.rules[2].pattern', value: '["git"]' },
        { path: 'a.rules[2].decision', value: 'prompt' },
      ]);
    });

    it('reads rules across several files, each under its own name', () => {
      expect(
        parsePermissionRules(
          [
            { name: 'a.rules', content: 'prefix_rule(pattern = ["ls"])' },
            {
              name: 'b.rules',
              content: '\nprefix_rule(\n  pattern = ["rm"],\n  decision = "forbidden")',
            },
          ],
          options
        )
      ).toMatchObject({
        parsed: true,
        fields: [
          { path: 'a.rules[1].pattern' },
          { path: 'a.rules[1].decision' },
          { path: 'b.rules[2].pattern' },
          { path: 'b.rules[2].decision' },
        ],
      });
    });

    const unparseable: readonly (readonly [string, string])[] = [
      ['prose that is not a call', 'not a rule'],
      ['an unterminated call', 'prefix_rule(\n  pattern = ["git",\n'],
      ['an unterminated string', 'prefix_rule(pattern = ["git, "status"])'],
      ['an unbalanced closer', 'prefix_rule(pattern = ["git"]])'],
      ['a call with no pattern', 'prefix_rule(decision = "allow")'],
      ['an empty pattern', 'prefix_rule(pattern = [])'],
      ['a pattern built from a variable', 'prefix_rule(pattern = GIT_STATUS)'],
      ['a pattern built by concatenation', 'prefix_rule(pattern = ["git"] + ["status"])'],
      ['a decision that is not a literal', 'prefix_rule(pattern = ["ls"], decision = DECISION)'],
      ['a positional argument', 'prefix_rule(["ls"])'],
      ['an assignment', 'COMMON = ["git"]'],
      ['a call this reader does not know', 'deny_rule(pattern = ["rm"])'],
      ['two calls on one line', 'prefix_rule(pattern = ["a"]) prefix_rule(pattern = ["b"])'],
      ['a pattern element that is a number', 'prefix_rule(pattern = ["git", 1])'],
    ];

    it.each(unparseable)(
      'reports %s as invalid-rules rather than dropping it',
      (_label, content) => {
        expect(parse(content)).toEqual({
          parsed: false,
          failureReason: 'invalid-rules',
          fields: [],
        });
      }
    );

    it('fails the whole source when one file is unparseable, not just that file', () => {
      expect(
        parsePermissionRules(
          [
            { name: 'good.rules', content: 'prefix_rule(pattern = ["ls"])' },
            { name: 'bad.rules', content: 'nonsense' },
          ],
          options
        )
      ).toEqual({ parsed: false, failureReason: 'invalid-rules', fields: [] });
    });
  });

  it('extracts a rule whose decision precedes its pattern', () => {
    expect(
      parsePermissionRules(
        [
          {
            name: 'default.rules',
            content: 'prefix_rule(decision = "deny", pattern = ["rm", "-rf"])',
          },
        ],
        { homeDir: '/home/ada' }
      )
    ).toEqual({
      parsed: true,
      fields: [
        {
          path: 'default.rules[1].pattern',
          presentation: 'value',
          value: '["rm", "-rf"]',
        },
        {
          path: 'default.rules[1].decision',
          presentation: 'value',
          value: 'deny',
        },
      ],
    });
  });

  it('reports an empty hooks object as a parsed source with zero fields', () => {
    expect(
      parseJsonSettings('{"hooks":{}}', {
        homeDir: '/home/ada',
        section: 'hooks',
      })
    ).toEqual({
      parsed: true,
      fields: [],
    });
  });

  it('leaves an excluded section to the source that owns it', () => {
    expect(
      parseJsonSettings('{"model":"sonnet","hooks":{"PreToolUse":[{"matcher":"Bash"}]}}', {
        homeDir: '/home/ada',
        excludeSections: ['hooks'],
      })
    ).toEqual({
      parsed: true,
      fields: [{ path: 'model', presentation: 'value', value: 'sonnet' }],
    });
  });

  it('projects nothing when a sectioned document is not an object', () => {
    expect(parseJsonSettings('[1,2]', { homeDir: '/home/ada', section: 'hooks' })).toEqual({
      parsed: true,
      fields: [],
    });
  });

  it('returns a typed failure instead of throwing for malformed TOML', () => {
    expect(parseTomlSettings('[projects.', { homeDir: '/home/ada' })).toEqual({
      parsed: false,
      failureReason: 'invalid-toml',
      fields: [],
    });
  });

  it('preserves TOML datetime leaves as stable values', () => {
    expect(
      parseTomlSettings('updated_at = 1979-05-27T07:32:00Z', {
        homeDir: '/home/ada',
      })
    ).toEqual({
      parsed: true,
      fields: [
        {
          path: 'updated_at',
          presentation: 'value',
          value: '1979-05-27T07:32:00.000Z',
        },
      ],
    });
  });
});
