import { describe, expect, it } from 'bun:test';
import { parseJsonSettings } from '../../../../src/modules/library/infrastructure/settings-parsers/json';
import { parsePermissionRules } from '../../../../src/modules/library/infrastructure/settings-parsers/rules';
import { parseTomlSettings } from '../../../../src/modules/library/infrastructure/settings-parsers/toml';

describe('settings parsers', () => {
  it('returns a typed failure instead of throwing for malformed JSON', () => {
    expect(parseJsonSettings('{"permissions":', { homeDir: '/home/ada' })).toEqual({
      parsed: false,
      failureReason: 'invalid-json',
      fields: [],
    });
  });

  it('collapses Codex project tables into a count', () => {
    const projects = Array.from(
      { length: 40 },
      (_, index) => `[projects."/home/ada/project-${index}"]\ntrust_level = "trusted"`
    ).join('\n\n');

    expect(parseTomlSettings(`model = "gpt-5"\n\n${projects}`, { homeDir: '/home/ada' })).toEqual({
      parsed: true,
      fields: [
        {
          path: 'model',
          presentation: 'value',
          value: 'gpt-5',
        },
        {
          path: 'projects.count',
          presentation: 'value',
          value: '40',
        },
      ],
    });
  });

  it('extracts rules as pattern-to-decision rows and ignores non-rules', () => {
    expect(
      parsePermissionRules(
        [
          {
            name: 'default.rules',
            content: [
              '# generated by Codex',
              '',
              'prefix_rule(pattern = ["git", "status"], decision = "allow")',
              'prefix_rule(pattern = ["rm"], decision = "deny")',
              'not a rule',
            ].join('\n'),
          },
        ],
        { homeDir: '/home/ada' }
      )
    ).toEqual({
      parsed: true,
      fields: [
        {
          path: 'default.rules[3].pattern',
          presentation: 'value',
          value: '["git", "status"]',
        },
        {
          path: 'default.rules[3].decision',
          presentation: 'value',
          value: 'allow',
        },
        {
          path: 'default.rules[4].pattern',
          presentation: 'value',
          value: '["rm"]',
        },
        {
          path: 'default.rules[4].decision',
          presentation: 'value',
          value: 'deny',
        },
      ],
    });
  });

  it('reports an empty hooks object as a parsed source with zero fields', () => {
    expect(
      parseJsonSettings('{"hooks":{}}', {
        homeDir: '/home/ada',
        section: 'hooks',
      })
    ).toEqual({
      parsed: true,
      fields: [],
    });
  });

  it('leaves an excluded section to the source that owns it', () => {
    expect(
      parseJsonSettings('{"model":"sonnet","hooks":{"PreToolUse":[{"matcher":"Bash"}]}}', {
        homeDir: '/home/ada',
        excludeSections: ['hooks'],
      })
    ).toEqual({
      parsed: true,
      fields: [{ path: 'model', presentation: 'value', value: 'sonnet' }],
    });
  });

  it('projects nothing when a sectioned document is not an object', () => {
    expect(parseJsonSettings('[1,2]', { homeDir: '/home/ada', section: 'hooks' })).toEqual({
      parsed: true,
      fields: [],
    });
  });

  it('returns a typed failure instead of throwing for malformed TOML', () => {
    expect(parseTomlSettings('[projects.', { homeDir: '/home/ada' })).toEqual({
      parsed: false,
      failureReason: 'invalid-toml',
      fields: [],
    });
  });

  it('preserves TOML datetime leaves as stable values', () => {
    expect(
      parseTomlSettings('updated_at = 1979-05-27T07:32:00Z', {
        homeDir: '/home/ada',
      })
    ).toEqual({
      parsed: true,
      fields: [
        {
          path: 'updated_at',
          presentation: 'value',
          value: '1979-05-27T07:32:00.000Z',
        },
      ],
    });
  });
});
